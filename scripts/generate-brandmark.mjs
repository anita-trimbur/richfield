/**
 * Generates src/content/brandmark.ts from src/content/brandmark.svg.
 *
 * The SVG must hold exactly two paths in the same coordinate space:
 * - the outline: one closed, filled path (the hand-drawn tapered stroke, which
 *   export converts to a filled shape), and
 * - the centerline: one open, stroked path following the pen from start to
 *   finish.
 *
 * SVG has no variable-width strokes, so BrandMark draws the mark on by
 * rebuilding the outline a little more each frame. That needs to know when
 * the pen reaches each outline point. This script splits the outline at its
 * two cap tips into two sides, then matches each side to the centerline with
 * dynamic time warping. The match only ever moves forward along both paths,
 * so where the stroke crosses itself a side can't jump to a different part of
 * the mark just because it passes nearby.
 *
 * Run `npm run brandmark` after changing the SVG.
 */
import { readFileSync, writeFileSync } from "node:fs";
import * as prettier from "prettier";

const SOURCE = "src/content/brandmark.svg";
const OUTPUT = "src/content/brandmark.ts";

/** Max length (viewBox units) of the straight pieces curves are split into. */
const FLATTEN_STEP = 0.02;
/** Points the centerline is resampled to; each is one step of pen progress. */
const CENTERLINE_SAMPLES = 1000;
/** Spacing (viewBox units) of outline points when matching them to the pen. */
const SIDE_SPACING = 0.05;
/** How far (viewBox units) output points may stray when dropping extras. */
const SIMPLIFY_TOLERANCE = 0.02;
/** How far (viewBox units of pen travel) simplifying may shift when a point is inked. */
const PROGRESS_TOLERANCE = 0.1;

const svg = readFileSync(SOURCE, "utf8");

const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
if (!viewBox) fail("the <svg> needs a viewBox");

const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map(([tag]) => ({
  d: tag.match(/\sd="([^"]*)"/)?.[1] ?? "",
  stroked: /\sstroke="(?!none")/.test(tag),
}));
const filled = paths.filter((path) => !path.stroked);
const stroked = paths.filter((path) => path.stroked);
if (filled.length !== 1 || stroked.length !== 1) {
  fail(
    `expected one filled outline and one stroked centerline, found ` +
      `${filled.length} filled and ${stroked.length} stroked paths`,
  );
}

const outlineData = filled[0].d.replace(/\s+/g, " ").trim();
const outline = onlySubpath(flattenPath(outlineData), "outline", true);
const centerline = onlySubpath(flattenPath(stroked[0].d), "centerline", false);

const pen = resample(centerline, CENTERLINE_SAMPLES);
const penLength = polylineLength(centerline);

const startTip = findCapTip(outline, pen);
const endTip = findCapTip(outline, pen.toReversed());
if (startTip === endTip) fail("couldn't find two separate cap tips");

const sides = [1, -1].map((direction) => {
  const edge = walk(outline, startTip, endTip, direction);
  const samples = resample(
    edge,
    Math.ceil(polylineLength(edge) / SIDE_SPACING) + 1,
  );
  const progress = matchToPen(samples, pen);
  const tagged = samples.map(([x, y], i) => [x, y, progress[i]]);
  return simplify(tagged, penLength).flatMap(([x, y, t]) => [
    round(x, 2),
    round(y, 2),
    round(t, 4),
  ]);
});

const source = `// Generated by scripts/generate-brandmark.mjs from brandmark.svg. Don't edit
// by hand: change the SVG and run \`npm run brandmark\`.

import type { StrokeSides } from "@/lib/stroke-outline";

/** Coordinate space shared by the outline and the side data. */
export const brandmarkViewBox = ${JSON.stringify(viewBox)};

/** The finished mark, exactly as exported. */
export const brandmarkOutline = ${JSON.stringify(outlineData)};

/** The outline's two edges, tagged with when the pen inks each point. */
export const brandmarkSides: StrokeSides = ${JSON.stringify(sides)};
`;

const config = await prettier.resolveConfig(OUTPUT);
writeFileSync(
  OUTPUT,
  await prettier.format(source, { ...config, filepath: OUTPUT }),
);
console.log(
  `Wrote ${OUTPUT}: sides of ${sides.map((side) => side.length / 3).join(" and ")} points`,
);

function fail(message) {
  throw new Error(`${SOURCE}: ${message}`);
}

/** The points of a path's single subpath, checking it's open or closed. */
function onlySubpath(subpaths, name, closed) {
  if (subpaths.length !== 1) {
    fail(`the ${name} must be one subpath, found ${subpaths.length}`);
  }
  if (subpaths[0].closed !== closed) {
    fail(`the ${name} must be ${closed ? "closed (end in Z)" : "open"}`);
  }
  const points = subpaths[0].points.filter(
    ([x, y], i, all) => i === 0 || x !== all[i - 1][0] || y !== all[i - 1][1],
  );
  const [first, last] = [points[0], points.at(-1)];
  if (closed && first[0] === last[0] && first[1] === last[1]) points.pop();
  return points;
}

/** Turns path data into subpaths of points, splitting curves into lines. */
function flattenPath(d) {
  const tokens =
    d.match(/[a-zA-Z]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/g) ?? [];
  const subpaths = [];
  let points;
  let i = 0;
  let command = "";
  let previous = "";
  let [x, y, startX, startY] = [0, 0, 0, 0];
  // The last curve control point, which S and T reflect.
  let control = [0, 0];

  const number = () => {
    const value = Number(tokens[i++]);
    if (Number.isNaN(value)) fail(`bad path data near "${tokens[i - 1]}"`);
    return value;
  };
  const lineTo = (toX, toY) => {
    points.push([toX, toY]);
    [x, y] = [toX, toY];
  };
  const curveTo = (controls, toX, toY) => {
    const hull = [[x, y], ...controls, [toX, toY]];
    const steps = Math.max(4, Math.ceil(polylineLength(hull) / FLATTEN_STEP));
    for (let step = 1; step <= steps; step++) {
      points.push(bezierPoint(hull, step / steps));
    }
    [x, y] = [toX, toY];
  };

  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) command = tokens[i++];
    const type = command.toUpperCase();
    // Lowercase commands are relative to the current point.
    const [dx, dy] = command === type ? [0, 0] : [x, y];
    if (type !== "M" && !points) fail("path data must start with M");

    switch (type) {
      case "M":
        x = startX = dx + number();
        y = startY = dy + number();
        points = [[x, y]];
        subpaths.push({ points, closed: false });
        // Extra coordinate pairs after a move are lines.
        command = command === "M" ? "L" : "l";
        break;
      case "L":
        lineTo(dx + number(), dy + number());
        break;
      case "H":
        lineTo(dx + number(), y);
        break;
      case "V":
        lineTo(x, dy + number());
        break;
      case "C": {
        const first = [dx + number(), dy + number()];
        control = [dx + number(), dy + number()];
        curveTo([first, control], dx + number(), dy + number());
        break;
      }
      case "S": {
        const first = /[CS]/.test(previous)
          ? [2 * x - control[0], 2 * y - control[1]]
          : [x, y];
        control = [dx + number(), dy + number()];
        curveTo([first, control], dx + number(), dy + number());
        break;
      }
      case "Q":
        control = [dx + number(), dy + number()];
        curveTo([control], dx + number(), dy + number());
        break;
      case "T":
        control = /[QT]/.test(previous)
          ? [2 * x - control[0], 2 * y - control[1]]
          : [x, y];
        curveTo([control], dx + number(), dy + number());
        break;
      case "Z":
        lineTo(startX, startY);
        subpaths.at(-1).closed = true;
        command = "";
        break;
      default:
        fail(
          command
            ? `unsupported path command "${command}"`
            : `unexpected "${tokens[i]}" after Z`,
        );
    }
    previous = type;
  }
  return subpaths;
}

/** Point at t (0–1) on a Bézier curve given as [start, ...controls, end]. */
function bezierPoint(hull, t) {
  let level = hull;
  while (level.length > 1) {
    level = level
      .slice(1)
      .map(([x, y], i) => [
        level[i][0] + (x - level[i][0]) * t,
        level[i][1] + (y - level[i][1]) * t,
      ]);
  }
  return level[0];
}

function polylineLength(points) {
  let length = 0;
  for (let i = 1; i < points.length; i++) {
    length += Math.hypot(
      points[i][0] - points[i - 1][0],
      points[i][1] - points[i - 1][1],
    );
  }
  return length;
}

/** `count` points spaced evenly along a polyline, ends included. */
function resample(points, count) {
  const total = polylineLength(points);
  const result = [points[0]];
  let segment = 1;
  let before = 0; // polyline length up to the start of `segment`
  for (let n = 1; n < count - 1; n++) {
    const target = (total * n) / (count - 1);
    let length;
    while (
      before +
        (length = Math.hypot(
          points[segment][0] - points[segment - 1][0],
          points[segment][1] - points[segment - 1][1],
        )) <
      target
    ) {
      before += length;
      segment++;
    }
    const k = length ? (target - before) / length : 0;
    const [ax, ay] = points[segment - 1];
    const [bx, by] = points[segment];
    result.push([ax + (bx - ax) * k, ay + (by - ay) * k]);
  }
  result.push(points.at(-1));
  return result;
}

/**
 * Index of the outline point at the tip of the cap around pen[0]: of the
 * points about as close to the pen's end as the stroke is wide, the one that
 * reaches furthest back past it.
 */
function findCapTip(outline, pen) {
  const [cx, cy] = pen[0];
  // A point a little way along the pen gives its direction at the end.
  const [ax, ay] =
    pen.find(([x, y]) => Math.hypot(x - cx, y - cy) >= 0.5) ?? pen.at(-1);
  const along = Math.hypot(ax - cx, ay - cy);
  const [backX, backY] = [(cx - ax) / along, (cy - ay) / along];

  const distances = outline.map(([x, y]) => Math.hypot(x - cx, y - cy));
  const capRadius = Math.min(...distances);
  let tip = -1;
  let reach = -Infinity;
  outline.forEach(([x, y], i) => {
    if (distances[i] > capRadius * 1.6) return;
    const pointReach = (x - cx) * backX + (y - cy) * backY;
    if (pointReach > reach) [tip, reach] = [i, pointReach];
  });
  return tip;
}

/** Outline points from index `from` to `to`, stepping in `direction`. */
function walk(outline, from, to, direction) {
  const edge = [];
  for (let i = from; ; i = (i + direction + outline.length) % outline.length) {
    edge.push(outline[i]);
    if (i === to) return edge;
  }
}

/**
 * Pen progress (0–1) for each side point, by dynamic time warping: the
 * cheapest pairing of side points with pen points, by total distance, that
 * starts at both starts, ends at both ends, and never steps backwards.
 */
function matchToPen(side, pen) {
  const [rows, cols] = [side.length, pen.length];
  const cost = new Float64Array(rows * cols);
  const at = (r, c) => (r < 0 || c < 0 ? Infinity : cost[r * cols + c]);
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const distance = Math.hypot(
        side[r][0] - pen[c][0],
        side[r][1] - pen[c][1],
      );
      const cheapest =
        r || c ? Math.min(at(r - 1, c - 1), at(r - 1, c), at(r, c - 1)) : 0;
      cost[r * cols + c] = distance + cheapest;
    }
  }

  // Trace the cheapest pairing back from the ends, recording the range of
  // pen points each side point was paired with.
  const first = new Array(rows).fill(cols);
  const last = new Array(rows).fill(-1);
  let [r, c] = [rows - 1, cols - 1];
  for (;;) {
    first[r] = Math.min(first[r], c);
    last[r] = Math.max(last[r], c);
    if (r === 0 && c === 0) break;
    const diagonal = at(r - 1, c - 1);
    const up = at(r - 1, c);
    const left = at(r, c - 1);
    if (diagonal <= up && diagonal <= left) [r, c] = [r - 1, c - 1];
    else if (up <= left) r--;
    else c--;
  }
  return first.map((start, i) => (start + last[i]) / 2 / (cols - 1));
}

/**
 * Drops points that barely change the shape (Ramer–Douglas–Peucker). Pen
 * progress counts as a third dimension, scaled so PROGRESS_TOLERANCE of pen
 * travel weighs the same as SIMPLIFY_TOLERANCE of distance.
 */
function simplify(points, penLength) {
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const spans = [[0, points.length - 1]];
  while (spans.length) {
    const [a, b] = spans.pop();
    let furthest = -1;
    let furthestDistance = SIMPLIFY_TOLERANCE;
    for (let i = a + 1; i < b; i++) {
      const distance = distanceToSegment(
        points[i],
        points[a],
        points[b],
        penLength,
      );
      if (distance > furthestDistance)
        [furthest, furthestDistance] = [i, distance];
    }
    if (furthest >= 0) {
      keep[furthest] = 1;
      spans.push([a, furthest], [furthest, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

function distanceToSegment(
  [px, py, pt],
  [ax, ay, at],
  [bx, by, bt],
  penLength,
) {
  const [pz, az, bz] = [pt, at, bt].map(
    (t) => (t * penLength * SIMPLIFY_TOLERANCE) / PROGRESS_TOLERANCE,
  );
  const [ex, ey, ez] = [bx - ax, by - ay, bz - az];
  const lengthSquared = ex * ex + ey * ey + ez * ez;
  const k = lengthSquared
    ? Math.max(
        0,
        Math.min(
          1,
          ((px - ax) * ex + (py - ay) * ey + (pz - az) * ez) / lengthSquared,
        ),
      )
    : 0;
  return Math.hypot(px - ax - ex * k, py - ay - ey * k, pz - az - ez * k);
}

function round(value, decimals) {
  return Number(value.toFixed(decimals));
}
